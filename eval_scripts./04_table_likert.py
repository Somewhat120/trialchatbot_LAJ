import os
import json
import pandas as pd
import glob
import re

# ==========================================
# ⚙️ CONFIGURATION
# ==========================================
# Can handle both organized structure (prompt_comp_results_Likert) 
# and messy structure (prompt_comp_results_Likert_add_round1)
INPUT_ROOT = "prompt_comp_results_Likert"  # Set to root, will walk all criterion folders
OUTPUT_DIR = "eval_results"

# ==========================================
# 🛠️ PARSING HELPERS
# ==========================================
def parse_strategy_key(key_string):
    """
    Extracts metadata (Strategy, Length, RAG status) from the complex JSON keys.
    Example Key: "oracle_baseline__short_v1_RAG_1224"
    """
    meta = {
        "Base_Strategy": "Unknown",
        "Prompt_Length": "-",
        "RAG_Type": "-"
    }
    
    # 1. Identify Base Strategy
    # Order matters: check longer/specific ones first
    # Check for demo variants first (they have _RAG_demo or _demo pattern)
    has_demo = "_demo" in key_string or key_string.endswith("demo")
    
    if "def_cot" in key_string:
        meta["Base_Strategy"] = "def_cot_demo" if has_demo else "def_cot"
    elif "def_demo" in key_string:
        meta["Base_Strategy"] = "def_demo"
    elif "def_only" in key_string:
        meta["Base_Strategy"] = "def_only"
    elif "baseline" in key_string:
        meta["Base_Strategy"] = "baseline_demo" if has_demo else "baseline"
    
    # 2. Identify Prompt Length / Variation (Mainly for 5_factual_acc)
    if "short_v1" in key_string:     meta["Prompt_Length"] = "short_v1"
    elif "short_v2" in key_string:   meta["Prompt_Length"] = "short_v2"
    elif "long" in key_string:       meta["Prompt_Length"] = "long"
    
    # 3. Identify RAG Status
    if "NO_RAG" in key_string:       meta["RAG_Type"] = "NO_RAG"
    elif "_RAG_" in key_string or key_string.endswith("_RAG"): meta["RAG_Type"] = "RAG"
    
    return meta

def flatten_metrics(metrics_dict):
    """
    Flattens nested Likert metrics.
    Skips the 5x5 Confusion Matrix to keep the table readable.
    """
    flat_data = {}
    
    # We explicitly look for the scalar dictionaries generated by the Likert script
    categories = ['correlations', 'accuracy', 'reliability', 'error']
    
    for cat in categories:
        if cat in metrics_dict and isinstance(metrics_dict[cat], dict):
            for sub_key, value in metrics_dict[cat].items():
                # Col Name: accuracy_exact_match
                flat_data[f"{cat}_{sub_key}"] = value
    
    # Also grab 'n' (sample size)
    if 'n' in metrics_dict:
        flat_data['n'] = metrics_dict['n']
        
    return flat_data

def extract_criterion_from_folder(folder_name):
    """Extract criterion name from folder name, handling various formats."""
    # Remove model suffixes
    folder_name = re.sub(r'_(medgemma|gpt5|qwen3|qwen)$', '', folder_name, flags=re.IGNORECASE)
    
    # Handle special cases
    if folder_name == "4_transparency":
        return "4_transparent"
    elif folder_name in ["5__5", "5_only_qwen", "5_testn5_"]:
        return "5_factual_acc"
    
    return folder_name

def extract_model_name(folder_name, filename):
    """Extract model name from folder name or filename."""
    # First try filename
    model_from_file = os.path.splitext(filename)[0]
    if model_from_file.upper() in ["GPT5", "MEDGEMMA", "QWEN", "QWEN3"]:
        # Normalize
        if model_from_file.upper() == "QWEN3":
            return "qwen"
        elif model_from_file.upper() == "GPT5":
            return "GPT5"
        else:
            return model_from_file.lower()
    
    # Try from folder name
    match = re.search(r'_(medgemma|gpt5|qwen3|qwen)$', folder_name, re.IGNORECASE)
    if match:
        model = match.group(1).lower()
        if model == "qwen3":
            return "qwen"
        elif model == "gpt5":
            return "GPT5"
        return model
    
    # Default: use filename
    return model_from_file

def process_criterion_folder(folder_path, criterion_name):
    """Reads all JSONs in a folder and compiles them into a DataFrame."""
    json_files = glob.glob(os.path.join(folder_path, "*.json"))
    
    if not json_files:
        return None

    all_rows = []
    folder_basename = os.path.basename(folder_path)
    
    for file_path in json_files:
        filename = os.path.basename(file_path)
        # Get Model Name from filename or folder name
        model_name = extract_model_name(folder_basename, filename)
        
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
            
            # Iterate through strategies inside the file
            for key_string, metrics in data.items():
                
                # 1. Parse the complex key
                meta = parse_strategy_key(key_string)
                
                row = {
                    "Criterion": criterion_name,
                    "Model": model_name,
                    "Full_Key": key_string,  # Keep original key just in case
                    "Base_Strategy": meta["Base_Strategy"],
                    "Prompt_Length": meta["Prompt_Length"],
                    "RAG_Type": meta["RAG_Type"]
                }
                
                # 2. Add Flattened Metrics
                if metrics: # Ensure metrics is not None
                    flat_metrics = flatten_metrics(metrics)
                    row.update(flat_metrics)
                    all_rows.append(row)
                
        except Exception as e:
            print(f"❌ Error reading {file_path}: {e}")

    if not all_rows:
        return None

    # Create DataFrame
    df = pd.DataFrame(all_rows)
    
    # Reorder columns for readability
    cols = list(df.columns)
    
    # Define ideal order
    priority = [
        "Criterion", "Model", "Base_Strategy", "Prompt_Length", "RAG_Type", "n",
        "correlations_pearson", "correlations_spearman",
        "accuracy_exact_match", "accuracy_within_1_point",
        "reliability_kappa_linear", "reliability_kappa_quadratic",
        "error_mae"
    ]
    
    # Construct final column list (Priority + whatever else is left)
    final_cols = [c for c in priority if c in cols] + [c for c in cols if c not in priority and c != "Full_Key"]
    
    return df[final_cols]

# ==========================================
# 🚀 MAIN EXECUTION
# ==========================================
def main():
    print(f"🚀 Scanning root: {INPUT_ROOT}")
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    
    # First pass: collect all folders and group by criterion
    criterion_folders = {}  # criterion_name -> list of folder paths
    
    for root, dirs, files in os.walk(INPUT_ROOT):
        # Check if this folder has JSON files
        json_files = [f for f in files if f.endswith(".json")]
        
        if len(json_files) > 0:
            folder_basename = os.path.basename(root)
            
            # Skip root itself
            if root == INPUT_ROOT: 
                continue
            
            # Extract criterion name (handles both organized and messy structures)
            criterion_name = extract_criterion_from_folder(folder_basename)
            
            if criterion_name not in criterion_folders:
                criterion_folders[criterion_name] = []
            criterion_folders[criterion_name].append(root)
    
    # Second pass: process each criterion (consolidating multiple folders if needed)
    processed_count = 0
    
    for criterion_name, folder_paths in criterion_folders.items():
        print(f"\n📂 Processing Criterion: {criterion_name} ({len(folder_paths)} folder(s))")
        
        all_rows = []
        
        # Process all folders for this criterion
        for folder_path in folder_paths:
            folder_basename = os.path.basename(folder_path)
            print(f"   Processing folder: {folder_basename}")
            
            json_files = glob.glob(os.path.join(folder_path, "*.json"))
            
            for file_path in json_files:
                filename = os.path.basename(file_path)
                model_name = extract_model_name(folder_basename, filename)
                
                try:
                    with open(file_path, 'r', encoding='utf-8') as f:
                        data = json.load(f)
                    
                    # Iterate through strategies inside the file
                    for key_string, metrics in data.items():
                        # Parse the complex key
                        meta = parse_strategy_key(key_string)
                        
                        row = {
                            "Criterion": criterion_name,
                            "Model": model_name,
                            "Full_Key": key_string,
                            "Base_Strategy": meta["Base_Strategy"],
                            "Prompt_Length": meta["Prompt_Length"],
                            "RAG_Type": meta["RAG_Type"]
                        }
                        
                        # Add Flattened Metrics
                        if metrics:
                            flat_metrics = flatten_metrics(metrics)
                            row.update(flat_metrics)
                            all_rows.append(row)
                            
                except Exception as e:
                    print(f"   ❌ Error reading {file_path}: {e}")
        
        if all_rows:
            # Create DataFrame
            df = pd.DataFrame(all_rows)
            
            # Reorder columns for readability
            cols = list(df.columns)
            priority = [
                "Criterion", "Model", "Base_Strategy", "Prompt_Length", "RAG_Type", "n",
                "correlations_pearson", "correlations_spearman",
                "accuracy_exact_match", "accuracy_within_1_point",
                "reliability_kappa_linear", "reliability_kappa_quadratic",
                "error_mae"
            ]
            final_cols = [c for c in priority if c in cols] + [c for c in cols if c not in priority and c != "Full_Key"]
            
            # Save to CSV
            output_filename = f"table_Likert_{criterion_name}.csv"
            output_path = os.path.join(OUTPUT_DIR, output_filename)
            
            df[final_cols].to_csv(output_path, index=False)
            print(f"  ✅ Saved table ({len(df)} rows) to: {output_path}")
            processed_count += 1
        else:
            print(f"  ⚠️ No valid data found in {criterion_name}")

    print(f"\n✨ COMPLETED. Created {processed_count} tables in '{OUTPUT_DIR}'")

if __name__ == "__main__":
    main()